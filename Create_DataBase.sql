
-- SGBD: Oracle Database 21c
-- Schema: INVENTORYMANAGEMENT

-- Tabela VOLUME (Independente)
CREATE TABLE VOLUME (
    CODVOL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRVOL VARCHAR2(100) NOT NULL
);

-- Tabela LOCAL (Independente)
CREATE TABLE LOCAL (
    CODLOCAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRLOCAL VARCHAR2(100) NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL
);

-- Tabela PARCEIRO (Independente)
CREATE TABLE PARCEIRO (
    CODPARC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMEPARC VARCHAR2(150) NOT NULL,
    RAZAOSOCIAL VARCHAR2(150),
    TIPPESSOA VARCHAR2(20),
    TELEFONE VARCHAR2(30),
    CPF_CNPJ VARCHAR2(20),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    DHCAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DHALTER TIMESTAMP
);

-- Tabela USUARIO (Independente)
CREATE TABLE USUARIO (
    CODUSU NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMEUSU VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150),
    SENHA VARCHAR2(100),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL
);

-- Tabela PRODUTO (Depende de VOLUME)
CREATE TABLE PRODUTO (
    CODPROD NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRPROD VARCHAR2(150) NOT NULL,
    CODVOL NUMBER NOT NULL,
    MARCA VARCHAR2(50),
    PRECO NUMBER(12,2) DEFAULT 0 NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    DHCAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DHALTER TIMESTAMP,
    CONSTRAINT FK_PRODUTO_VOLUME FOREIGN KEY (CODVOL) REFERENCES VOLUME(CODVOL)
);

-- Tabela Associativa FORNECEDOR (Depende de PRODUTO e PARCEIRO)
CREATE TABLE FORNECEDOR (
    CODPROD NUMBER NOT NULL,
    CODPARC NUMBER NOT NULL,
    CUSTO NUMBER(12,4),
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY (CODPROD, CODPARC),
    CONSTRAINT FK_FORN_PRODUTO FOREIGN KEY (CODPROD) REFERENCES PRODUTO(CODPROD),
    CONSTRAINT FK_FORN_PARCEIRO FOREIGN KEY (CODPARC) REFERENCES PARCEIRO(CODPARC)
);

-- Tabela Associativa ESTOQUE (Depende de PRODUTO e LOCAL)
CREATE TABLE ESTOQUE (
    CODPROD NUMBER NOT NULL,
    CODLOCAL NUMBER NOT NULL,
    ESTOQUE NUMBER(12,4) DEFAULT 0 NOT NULL,
    ESTMIN NUMBER(12,4) DEFAULT 0 NOT NULL,
    ESTMAX NUMBER(12,4) DEFAULT 0 NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_ESTOQUE PRIMARY KEY (CODPROD, CODLOCAL),
    CONSTRAINT FK_EST_PRODUTO FOREIGN KEY (CODPROD) REFERENCES PRODUTO(CODPROD),
    CONSTRAINT FK_EST_LOCAL FOREIGN KEY (CODLOCAL) REFERENCES LOCAL(CODLOCAL)
);